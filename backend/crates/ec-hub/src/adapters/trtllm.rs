/// `_inferred_max_seq_len`: what the engine derives from the model config when `max_seq_len` is unset or too big
/// (`DecoderModelForCausalLM.infer_max_seq_len`). Without a config dict only `max_position_embeddings` is known.
pub fn inferred_max_seq_len(model: &ModelInfo) -> PyResult<Option<Int>> {
    let cfg = &model.raw_config;
    if cfg.is_empty() {
        return Ok(model
            .max_position_embeddings
            .filter(|p| *p > 0)
            .map(|p| Int::from_i128(i128::from(p))));
    }
    let pos_of = |v: Option<&Value>| v.and_then(Value::as_i64).filter(|p| *p > 0);
    let text = cfg.get("text_config").and_then(Value::as_object);
    let pos = match cfg.get("max_position_embeddings") {
        None | Some(Value::Null) => text.and_then(|t| t.get("max_position_embeddings")),
        p => p,
    };
    let inferred = pos_of(pos).unwrap_or(2048);
    let mut factor = 1.0;
    if let Some(scaling) = cfg.get("rope_scaling").and_then(Value::as_object) {
        let rope_type = match scaling.get("type") {
            Some(t) => Some(t),
            None => scaling.get("rope_type"),
        };
        let known = rope_type
            .and_then(Value::as_str)
            .is_some_and(|t| matches!(t, "su" | "longrope" | "llama3" | "yarn"));
        let raw_factor = match scaling.get("factor") {
            Some(f) => Num::of(f),
            None => Some(Num::Float(1.0)),
        };
        if !known
            && let Some(f) = raw_factor
            && f.gt(0.0)
        {
            factor = f.f();
        }
    }
    if factor == 1.0 {
        return Ok(Some(Int::from_i128(i128::from(inferred))));
    }
    // math.ceil(inferred * factor): OverflowError when the product is infinite
    #[allow(clippy::cast_precision_loss)]
    let x = (inferred as f64 * factor).ceil();
    Int::from_f64(x)
        .map(Some)
        .ok_or_else(|| exc("OverflowError", "cannot convert float infinity to integer"))
}

/// `_as_float(val, default)`: a finite number, or `default` (compatibility() and memory_model() may see unvalidated
/// parameters).
fn as_float(val: Option<&Value>, default: f64) -> f64 {
    val.and_then(Num::of)
        .map(Num::f)
        .filter(|f| f.is_finite())
        .unwrap_or(default)
}

/// `_as_int(val, default)` = `int(_as_float(val, float(default)))`, exact (Python's ints are unbounded).
#[allow(clippy::cast_precision_loss)]
fn as_int(val: Option<&Value>, default: i128) -> Int {
    Int::from_f64(as_float(val, default as f64)).unwrap_or_else(Int::zero)
}

/// `_set_path(tree, "a.b.c", value)`: set a nested key, creating the parents.
fn set_path(tree: &mut Vec<(String, PyVal)>, path: &str, value: PyVal) -> Result<(), String> {
    let parts: Vec<&str> = path.split('.').collect();
    let (last, parents) = parts.split_last().ok_or_else(String::new)?;
    let mut node = tree;
    for part in parents {
        let idx = match node.iter().position(|(k, _)| k == part) {
            Some(i) => {
                match &node[i].1 {
                    PyVal::None => {
                        return Err(format!(
                            "{path}: '{part}' is switched off, so it cannot carry settings"
                        ));
                    }
                    PyVal::Dict(_) => {}
                    _ => return Err(format!("{path}: '{part}' is already set to a value")),
                }
                i
            }
            None => {
                node.push(((*part).to_string(), PyVal::Dict(Vec::new())));
                node.len() - 1
            }
        };
        node = match &mut node[idx].1 {
            PyVal::Dict(d) => d,
            _ => return Err(format!("{path}: '{part}' is already set to a value")),
        };
    }
    PyVal::set(node, last, value);
    Ok(())
}

/// `_json_obj(val)`: a JSON-typed parameter as a Python object (a str is parsed).
fn json_obj(val: &Value) -> PyResult<PyVal> {
    match val {
        Value::String(s) => py::json_loads(s),
        other => Ok(PyVal::from_json(other)),
    }
}

/// `int(x)` of a validated int-list entry (a str of digits or an int).
fn int_entry(x: &Value) -> PyResult<PyVal> {
    match x {
        Value::String(s) => Ok(PyVal::Int(py::int_digits(s)?)),
        other => Ok(Num::of(other).map_or(PyVal::None, |n| PyVal::Int(n.int_str()))),
    }
}

