/// `^...$` of Python's `re.match`: `$` also matches before one final newline.
static IMAGE_RE: LazyLock<Regex> = LazyLock::new(|| {
    py::pyre(r"^[A-Za-z0-9][A-Za-z0-9._\-/]*(:\d+)?(/[A-Za-z0-9._\-/]+)*:[A-Za-z0-9._\-]+\n?\z")
});
/// one token: no whitespace or control characters
static SAFE_VALUE: LazyLock<Regex> = LazyLock::new(|| py::pyre(r"^[^\s\x00-\x1f\x7f]+\n?\z"));

/// `_KV_BYTES` (nvfp4: 4 bits + one FP8 scale per 16 values).
fn kv_bytes(name: &str) -> Option<f64> {
    match name {
        "auto" => Some(2.0),
        "fp8" => Some(1.0),
        "nvfp4" => Some(0.5625),
        _ => None,
    }
}

