/// `KV_BYTES.get(name)`.
pub fn kv_bytes(name: &str) -> Option<f64> {
    KV_BYTES.iter().find(|(k, _)| *k == name).map(|(_, v)| *v)
}

/// The `_p()` helper (the flag is `env:<name>`).
pub struct P {
    spec: ParamSpec,
    expert: bool,
}

fn p(key: &str, name: &str, label: &str, help: &str, type_: &str, group: &str) -> P {
    P {
        spec: ParamSpec {
            key: key.into(),
            flag: format!("env:{name}"),
            label: label.into(),
            help: help.into(),
            type_: type_.into(),
            group: group.into(),
            default: Value::Null,
            choices: None,
            min: None,
            max: None,
            advanced: false,
            affects_memory: false,
            requires_restart: true,
            bool_style: "flag".into(),
            docs_url: Some(DOCS.into()),
            explain: None,
            level: None,
            unit: None,
        },
        expert: false,
    }
}

impl P {
    fn default(mut self, v: Value) -> Self {
        self.spec.default = v;
        self
    }
    fn choices(mut self, c: &[&str]) -> Self {
        self.spec.choices = Some(c.iter().map(|s| (*s).to_string()).collect());
        self
    }
    fn min(mut self, v: f64) -> Self {
        self.spec.min = Some(v);
        self
    }
    fn adv(mut self) -> Self {
        self.spec.advanced = true;
        self
    }
    fn mem(mut self) -> Self {
        self.spec.affects_memory = true;
        self
    }
    fn unit(mut self, u: &str) -> Self {
        self.spec.unit = Some(u.into());
        self
    }
    fn expert(mut self) -> Self {
        self.expert = true;
        self
    }
    fn docs(mut self, d: &str) -> Self {
        self.spec.docs_url = Some(d.into());
        self
    }
    /// `_p`: `expert` sets level "expert" and implies advanced.
    fn build(mut self) -> ParamSpec {
        if self.expert {
            self.spec.level = Some("expert".into());
            self.spec.advanced = true;
        }
        self.spec
    }
}

