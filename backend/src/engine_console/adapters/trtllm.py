    # ------------------------------------------------------------------ validation
    def validate(self, params: dict[str, Any]) -> list[str]:
        errs: list[str] = []
        for key, val in params.items():
            spec = self._by_key.get(key)
            if spec is None:
                errs.append(f"unknown parameter '{key}'")
                continue
            if val is None:
                continue
            errs.extend(self._check_value(spec, val))
        if errs:
            return errs
        errs.extend(self._check_relations(params))
        return errs

    def _check_value(self, spec: ParamSpec, val: Any) -> list[str]:
        k, t = spec.key, spec.type
        if t == "bool":
            return [] if isinstance(val, bool) else [f"{k}: expected true/false"]
        if t in ("int", "float"):
            if isinstance(val, bool) or not isinstance(val, (int, float)) or not math.isfinite(val):
                return [f"{k}: expected a number"]
            if t == "int" and int(val) != val:
                return [f"{k}: expected an integer"]
            if spec.min is not None and val < spec.min:
                return [f"{k}: must be >= {spec.min:g}"]
            if spec.max is not None and val > spec.max:
                return [f"{k}: must be <= {spec.max:g}"]
            if k == "tokens_per_block" and (int(val) & (int(val) - 1)):
                return [f"{k}: must be a power of two (the engine requires it)"]
            return []
        if t == "enum":
            if str(val) not in (spec.choices or []):
                return [f"{k}: '{val}' is not one of {', '.join(spec.choices or [])}"]
            return []
        if t == "string":
            return self._check_string(k, val)
        if t == "string_list":
            return self._check_list(k, val)
        if t == "json":
            return self._check_json(k, val)
        return []

    @staticmethod
    def _check_string(k: str, val: Any) -> list[str]:
        if not isinstance(val, str) or not val.strip():
            return [f"{k}: expected a non-empty string"]
        if k == "image":
            if not _IMAGE_RE.match(val) or val.endswith(":latest"):
                return ["image must be a pinned 'repo:tag' reference (never :latest)"]
            return []
        if k == "chat_template":
            if len(val) > 4000 or "\x00" in val:
                return [f"{k}: at most 4000 characters and no NUL (one argv entry)"]
            if val.startswith("-"):
                return [f"{k}: must not start with '-'"]
            # load_chat_template(): the value is opened as a file first; only a failure on a string that contains
            # one of { } or a newline makes the engine use it as the template itself.
            if not val.startswith("/") and not any(c in val for c in "{}\n"):
                return [f"{k}: use an absolute file path inside the container, or a Jinja template (it must contain "
                        "{, } or a newline, otherwise the engine reads it as a file name and stops)"]
            return []
        if k in _STRING_KEYS and (not _SAFE_VALUE.match(val) or val.startswith("-")):
            return [f"{k}: must be one token without spaces, not starting with '-'"]
        return []

    @staticmethod
    def _check_list(k: str, val: Any) -> list[str]:
        if not isinstance(val, list) or not val or not all(
                isinstance(x, (str, int)) and not isinstance(x, bool) and str(x).strip() for x in val):
            return [f"{k}: expected a non-empty list"]
        if k in _INT_LIST_KEYS and not all(str(x).isdigit() and int(x) > 0 for x in val):
            return [f"{k}: entries must be positive integers"]
        if k == "nvfp4_gemm_backends" and not all(str(x) in NVFP4_GEMM_BACKENDS for x in val):
            return [f"{k}: entries must be among {', '.join(NVFP4_GEMM_BACKENDS)}"]
        return []

    def _check_json(self, k: str, val: Any) -> list[str]:
        try:
            obj = json.loads(val) if isinstance(val, str) else val
        except json.JSONDecodeError as e:
            return [f"{k}: invalid JSON ({e.msg})"]
        if not isinstance(obj, dict) or not obj:
            return [f"{k}: expected a non-empty JSON object"]
        try:
            json.dumps(obj, allow_nan=False)
        except (TypeError, ValueError):
            return [f"{k}: only plain JSON values are allowed"]
        size = len(json.dumps(obj, separators=(",", ":")))
        limit = _MAX_ARGV_JSON_CHARS if k == "media_io_kwargs" else _MAX_YAML_JSON_CHARS
        if size > limit:
            return [f"{k}: {size} characters of JSON, at most {limit} (the node limits the size of what it passes on)"]
        if k == "speculative_config" and obj.get("decoding_type") not in SPEC_TYPES:
            return [f"{k}: needs a decoding_type of {', '.join(SPEC_TYPES)}"]
        if k == "extra_llm_options":
            return self._check_extra(obj)
        return []

    def _claimed_top_level(self) -> dict[str, str]:
        """Top-level YAML keys that a catalog parameter generates, with the parameter that owns each."""
        owner: dict[str, str] = {}
        for spec in self._catalog:
            if spec.flag.startswith(YAML_PREFIX) and spec.flag != YAML_EXTRA_FLAG:
                owner.setdefault(spec.flag[len(YAML_PREFIX):].split(".")[0], spec.key)
        # settings the CLI flags own: a YAML value would silently override the command line
        for spec in self._catalog:
            if spec.flag.startswith("--"):
                owner.setdefault(spec.flag[2:], spec.key)
        return owner

    def _check_extra(self, obj: dict[str, Any]) -> list[str]:
        errs: list[str] = []
        owner = self._claimed_top_level()
        for name in obj:
            if name in EXTRA_OPTIONS_DENIED:
                errs.append(f"extra_llm_options: '{name}' is not allowed ({EXTRA_OPTIONS_DENIED[name]})")
            elif name not in TORCH_LLM_ARGS_FIELDS:
                errs.append(f"extra_llm_options: '{name}' is not a setting of TensorRT-LLM "
                            f"{DEFAULT_IMAGE.rsplit(':', 1)[1]}; the engine refuses unknown names")
            elif name in owner:
                errs.append(f"extra_llm_options: '{name}' has its own parameter ({owner[name]})")
        return errs

    def _check_relations(self, p: dict[str, Any]) -> list[str]:
        errs: list[str] = []
        g = p.get
        # --- CUDA graphs / torch.compile
        if g("enable_cuda_graphs") is False and any(g(k) is not None for k in _CUDA_GRAPH_KEYS):
            errs.append("cuda_graph_* settings need enable_cuda_graphs to stay on")
        if g("cuda_graph_batch_sizes") and g("cuda_graph_max_batch_size"):
            errs.append("cuda_graph_batch_sizes and cuda_graph_max_batch_size cannot both be set "
                        "(the engine rejects the pair)")
        if g("enable_torch_compile") is not True and any(g(k) is not None for k in _COMPILE_KEYS):
            errs.append("torch_compile_* settings need enable_torch_compile=true")
        # --- speculative decoding
        errs.extend(self._check_speculation(p))
        # --- expert / MoE parallel sizes (Mapping: moe_tp * moe_ep * moe_cluster must equal tp)
        tp, ep, mt, cl = g("tensor_parallel_size") or 1, g("moe_expert_parallel_size"), \
            g("moe_tensor_parallel_size"), g("moe_cluster_parallel_size") or 1
        if cl > 1 and ep not in (None, 1):
            errs.append("moe_cluster_parallel_size > 1 requires moe_expert_parallel_size to be 1")
        elif ep is not None and mt is not None:
            if ep * mt * cl != tp:
                errs.append(f"moe_expert_parallel_size x moe_tensor_parallel_size x moe_cluster_parallel_size "
                            f"= {ep * mt * cl} must equal tensor_parallel_size = {tp}")
        elif (ep is not None or mt is not None or cl > 1) and tp % ((ep or mt or 1) * cl):
            errs.append(f"the MoE parallel sizes must divide tensor_parallel_size = {tp}")
        return errs

    @staticmethod
    def _check_speculation(p: dict[str, Any]) -> list[str]:
        g = p.get
        used = [k for k in _SHORTCUT_KEYS if g(k) is not None]
        if g("speculative_config") is not None:
            return ["speculative_config cannot be combined with the spec_* parameters"] if used else []
        if not used:
            return []
        kind = g("spec_decoding_type")
        if kind is None:
            return ["the spec_* parameters need spec_decoding_type"]
        errs: list[str] = []
        needs: dict[str, tuple[str, ...]] = {
            "Eagle": ("spec_draft_model", "spec_max_draft_len"),
            "DraftTarget": ("spec_draft_model", "spec_max_draft_len"),
            "NGram": ("spec_max_draft_len", "spec_ngram_max_matching_size"),
        }
        errs += [f"{kind} speculation needs {k}" for k in needs.get(kind, ()) if g(k) is None]
        only: dict[str, tuple[str, ...]] = {
            "spec_ngram_max_matching_size": ("NGram",), "spec_num_nextn_predict_layers": ("MTP",),
            "spec_eagle3_one_model": ("Eagle",), "spec_draft_model": ("Eagle", "DraftTarget", "MTP"),
            "spec_max_draft_len": ("Eagle", "DraftTarget", "NGram"),
        }
        errs += [f"{k} does not apply to {kind} speculation" for k, kinds in only.items()
                 if g(k) is not None and kind not in kinds]
        if kind == "AUTO" and any(g(k) is not None for k in _SHORTCUT_KEYS[1:]):
            errs.append("AUTO speculation takes no other spec_* settings (the engine ignores them)")
        return errs

    # ------------------------------------------------------------------ launch
    def _speculation_kind(self, p: dict[str, Any]) -> str | None:
        raw = p.get("speculative_config")
        if raw is not None:
            try:
                obj = _json_obj(raw)
            except json.JSONDecodeError:
                return None
            return str(obj.get("decoding_type")) if isinstance(obj, dict) and obj.get("decoding_type") else None
        kind = p.get("spec_decoding_type")
        return str(kind) if kind else None

    def _yaml_tree(self, p: dict[str, Any]) -> dict[str, Any]:
        """The options file as a dict. Empty when nothing needs it."""
        tree: dict[str, Any] = {}
        # Iteration statistics: on unless the user turned them off (false is the engine default, so it needs no key).
        stats = p.get("enable_iter_perf_stats")
        if stats or (stats is None and _METRICS_ON_BY_DEFAULT):
            tree["enable_iter_perf_stats"] = True
        for spec in self._catalog:
            if not spec.flag.startswith(YAML_PREFIX) or spec.flag == YAML_EXTRA_FLAG:
                continue
            if spec.key == "enable_iter_perf_stats":
                continue
            val = p.get(spec.key)
            if val is None:
                continue
            path = spec.flag[len(YAML_PREFIX):]
            if spec.key == "enable_cuda_graphs":
                if not val:
                    tree[path] = None                  # `cuda_graph_config: null` is how the engine turns them off
                continue
            if spec.key == "enable_torch_compile":
                if val:
                    tree.setdefault(path, {})
                continue
            if spec.key == "speculative_config":
                tree[path] = _json_obj(val)
            elif spec.key in ("kv_cache_max_gib", "kv_host_cache_gib"):
                _set_path(tree, path, _gib_to_bytes(val))
            elif spec.key in _INT_LIST_KEYS:
                _set_path(tree, path, _int_list(val))
            elif spec.key == "nvfp4_gemm_backends":
                _set_path(tree, path, [str(x) for x in val])
            elif spec.type == "int":
                _set_path(tree, path, int(val))
            elif spec.type == "float":
                _set_path(tree, path, float(val))
            elif spec.type == "bool":
                _set_path(tree, path, bool(val))
            else:
                _set_path(tree, path, str(val))
        if tree.get("enable_iter_perf_stats") and "max_stats_len" not in tree:
            tree["max_stats_len"] = _STATS_HISTORY
        sched = tree.get("scheduler_config")
        if isinstance(sched, dict):
            for key, default in _SCHEDULER_DEFAULTS.items():
                sched.setdefault(key, json.loads(json.dumps(default)))
        extra = p.get("extra_llm_options")
        if extra is not None:
            for key, value in _json_obj(extra).items():
                if key in tree:
                    raise ValueError(f"extra_llm_options: '{key}' is already set by a parameter")
                tree[key] = value
        return tree

    @staticmethod
    def _render_yaml(tree: dict[str, Any]) -> str:
        return _YAML_HEADER + yaml.safe_dump(tree, sort_keys=True, default_flow_style=False)

    def _cli(self, spec: ParamSpec, val: Any) -> list[str]:
        """argv tokens for one `--flag` parameter. Booleans are plain flags: the CLI has no `--no-` form."""
        if spec.type == "bool":
            return [spec.flag] if val else []
        if spec.type == "json":
            return [spec.flag, json.dumps(_json_obj(val), separators=(",", ":"))]
        if spec.type == "float":
            return [spec.flag, format(float(val), "g")]
        if spec.type == "int":
            return [spec.flag, str(int(val))]
        return [spec.flag, str(val)]

    def build_launch_ctx(self, ctx: LaunchContext) -> LaunchSpec:
        if ctx.model_format not in self.model_formats:
            raise ValueError(f"TensorRT-LLM loads Hugging Face checkpoints (hf) or local model folders (plain), "
                             f"not '{ctx.model_format}'")
        errs = self.validate(ctx.params)
        if errs:
            raise ValueError("; ".join(errs))
        plain = ctx.model_format == "plain"
        model = ctx.model_path if plain else ctx.model
        if not model or model.startswith("-") or not _SAFE_VALUE.match(model):
            raise ValueError("the model reference must be one token that does not start with '-'")
        p = ctx.params
        argv = ["trtllm-serve", "serve", model, "--backend", "pytorch",
                "--host", "0.0.0.0",  # noqa: S104 (container-internal; the core publishes to loopback)
                "--port", str(_CONTAINER_PORT)]
        # Offline by design: the engine network has no egress, and a hub look-up would only time out. The HF root is
        # mounted read-only; telemetry stays off (deny-by-default egress).
        # PYTHONUNBUFFERED: the engine's `print` lines (for example "Model init total -- 21.34s") would otherwise sit in
        # a block buffer while stdout is a pipe, and the console's start-up progress would lag behind the engine.
        env = {"HF_HUB_OFFLINE": "1", "HF_HUB_DISABLE_TELEMETRY": "1", "DO_NOT_TRACK": "1", "PYTHONUNBUFFERED": "1"}
        if not plain:
            env["HF_HOME"] = ctx.hf_cache_container_path
        image = self.default_image
        for spec in self._catalog:
            val = p.get(spec.key)
            if val is None:
                continue
            if spec.flag == "@image":
                image = str(val)
            elif spec.flag.startswith("env:"):
                if spec.type == "bool":
                    if val:
                        env[spec.flag[4:]] = "1"
                else:
                    env[spec.flag[4:]] = str(val)
            elif spec.flag.startswith("--"):
                argv += self._cli(spec, val)
        files: dict[str, str] = {}
        tree = self._yaml_tree(p)
        if tree:
            files[EXTRA_OPTIONS_PATH] = self._render_yaml(tree)
            argv += ["--extra_llm_api_options", EXTRA_OPTIONS_PATH]
        # The image's own banner asks for a 64 MiB stack (as NVIDIA's documented docker command does); memlock is not
        # requested: nodes refuse it, and it only matters for RDMA transports.
        return LaunchSpec(image=image, argv=argv, env=env, container_port=_CONTAINER_PORT, health_path="/health",
                          metrics_path="/metrics", models_path="/v1/models", shm_size="16g", ipc_host=True,
                          files=files, needs_hf_cache=not plain, ulimits={"stack": "67108864"})

    def build_launch(self, model: str, params: dict[str, Any], hw: Hardware, *, served_name: str,
                     hf_cache_container_path: str) -> LaunchSpec:
        return self.build_launch_ctx(LaunchContext(model=model, model_format="hf", served_name=served_name,
                                                   hf_cache_container_path=hf_cache_container_path,
                                                   params=params, hw=hw))

    # ------------------------------------------------------------------ compatibility
    @staticmethod
    def _world(p: dict[str, Any]) -> tuple[int, int, int]:
        g = p.get
        return (max(1, _as_int(g("tensor_parallel_size"), 1)), max(1, _as_int(g("pipeline_parallel_size"), 1)),
                max(1, _as_int(g("context_parallel_size"), 1)))

    @staticmethod
    def _family(model: ModelInfo) -> str:
        return " ".join([model.repo_id, model.model_type or "", *model.architectures]).lower()

    @staticmethod
    def _is_multimodal(model: ModelInfo) -> bool:
        if model.pipeline_tag in ("image-text-to-text", "any-to-any", "video-text-to-text"):
            return True
        return any(any(m in a.lower() for m in _MULTIMODAL_MARKERS) for a in model.architectures)

    def compatibility(self, model: ModelInfo, params: dict[str, Any], hw: Hardware) -> list[Compat]:
        out: list[Compat] = []

        def add(lvl: Literal["ok", "warn", "block"], code: str, msg: str) -> None:
            out.append(Compat(level=lvl, code=code, message=msg))

        g = params.get
        tp, pp, cp = self._world(params)
        world = tp * pp * cp
        quant = (model.quantization or "").lower()
        cc_major = int(hw.compute_capability.split(".")[0]) if hw.compute_capability[:1].isdigit() else 0
        sm120 = cc_major == 12
        image = g("image") or self.default_image
        spec_kind = self._speculation_kind(params)

        archs = model.architectures
        if archs and archs[0] not in SUPPORTED_ARCHITECTURES:
            add("block", "unsupported_architecture",
                f"TensorRT-LLM {DEFAULT_IMAGE.rsplit(':', 1)[1]} has no model class for {archs[0]} (the PyTorch "
                f"backend registers {len(SUPPORTED_ARCHITECTURES)} architectures and rejects any other). Run this "
                "model on vLLM or SGLang, or pick a supported family such as Llama, Qwen3, Mistral or gpt-oss.")
        # --- parallelism
        if world > len(hw.gpu_ids):
            add("block", "world_exceeds_gpus",
                f"tensor x pipeline x context parallel = {world} but only {len(hw.gpu_ids)} GPU(s) are selected. "
                "Lower the parallel sizes or select more GPUs.")
        elif world < len(hw.gpu_ids):
            add("warn", "gpus_unused",
                f"{len(hw.gpu_ids)} GPUs are selected but this launch uses {world}; the rest stay reserved and "
                "idle. Raise tensor or pipeline parallel size, or select fewer GPUs.")
        if tp > 1:
            add("warn", "tp_over_pcie",
                "Tensor parallelism all-reduces over PCIe on every layer when the cards have no NVLink. "
                "TensorRT-LLM's own RTX PRO 6000 benchmarks used pipeline parallelism instead; prefer "
                "pipeline_parallel_size, or one model per card unless it does not fit.")
        heads = model.num_attention_heads
        if heads and tp * cp > 1 and not g("enable_attention_dp") and heads % (tp * cp):
            add("block", "tp_heads_indivisible",
                f"{heads} attention heads are not divisible by tensor x context parallel size {tp * cp} (the "
                "engine asserts this). Pick a divisor of the head count, or enable attention data parallel.")
        if pp > 1 and spec_kind in ("MTP", "Eagle"):
            add("block", "pp_with_speculation",
                f"{spec_kind} speculation does not work with pipeline parallelism (TensorRT-LLM's feature "
                "matrix says No). Use tensor parallelism or turn speculation off.")
        if g("sampler_type") == "TRTLLMSampler" and spec_kind in ("MTP", "Eagle"):
            add("block", "trtllm_sampler_conflict",
                f"TRTLLMSampler and {spec_kind} speculation cannot be enabled together; the engine stops at "
                "start-up. Set sampler_type to auto.")
        self._moe_rules(add, params, cc_major)
        self._quant_rules(add, model, params, quant, sm120, model.raw_config)
        # --- attention
        backend = g("attention_backend")
        if backend == "VANILLA":
            add("warn", "attention_backend_vanilla",
                "VANILLA is a reference attention implementation that NVIDIA does not recommend for production. "
                "Use TRTLLM (the default).")
        if backend == "FLASHINFER" and g("enable_block_reuse") is not False:
            add("warn", "attention_backend_flashinfer_reuse",
                "With the FlashInfer backend the engine switches KV block reuse (prefix caching) off by itself. "
                "Set enable_block_reuse=false to match, or use TRTLLM.")
        # --- context length
        msl, inferred = _as_int(g("max_seq_len"), 0), _inferred_max_seq_len(model)
        if msl and inferred and msl > inferred:
            add("warn", "max_seq_len_capped",
                f"max_seq_len {msl} is above the {inferred} tokens TensorRT-LLM infers from the model config. The "
                "engine lowers it without an error and has no option to extend a model's context, so the served "
                f"length would be {inferred}. Set max_seq_len to {inferred} or less.")
        # --- memory
        frac = _as_float(g("free_gpu_memory_fraction"), 0.9)
        if frac > 0.95:
            add("warn", "kv_cache_fraction_high",
                f"free_gpu_memory_fraction {frac:g} hands almost all remaining memory to the KV cache and leaves "
                "little for buffers that grow later; out-of-memory errors under load become likely. Use 0.9 or lower.")
        if model.weight_bytes and hw.gpu_total_gib:
            w = model.weight_bytes / _GIB / world
            if w > 0.95 * min(hw.gpu_total_gib):
                add("block", "weights_exceed_gpu",
                    f"The weights need about {w:.1f} GiB per GPU but a card holds {min(hw.gpu_total_gib):.1f} GiB, "
                    "and the PyTorch backend loads a checkpoint as it is (it ignores quantization settings). Pick an "
                    "FP8 or NVFP4 checkpoint, or shard over more GPUs.")
            else:
                for gid, free in zip(hw.gpu_ids, hw.gpu_free_gib, strict=False):
                    if w + 1.0 > free + 0.5:
                        add("block", "insufficient_free_vram",
                            f"GPU {gid}: the weights need about {w:.1f} GiB but only {free:.1f} GiB is free. Stop "
                            "the engine that holds the memory, or select a card with more free memory.")
                        break
        if model.weight_bytes and hw.host_ram_gib and model.weight_bytes / _GIB > 0.4 * hw.host_ram_gib:
            add("warn", "weights_prefetch_host_ram",
                f"Before loading, TensorRT-LLM reads the checkpoint files into host memory (up to 16 files at once "
                f"per GPU worker), so start-up can briefly need about as much free RAM as the checkpoint: "
                f"{model.weight_bytes / _GIB:.0f} GiB of this machine's {hw.host_ram_gib:.0f} GiB. Stop "
                "memory-heavy programs first. The engine skips this read-ahead when the checkpoint is larger "
                "than 90 % of the RAM that is free.")
        if g("trust_remote_code"):
            add("warn", "trust_remote_code",
                "trust_remote_code runs Python from the model repository. Only enable it for repositories you "
                "have reviewed.")
        self._parser_rules(add, model, params)
        # --- misc
        if g("enable_iter_perf_stats") is False:
            add("warn", "iter_stats_off",
                "Iteration statistics are off, so the console's metrics page and KV-cache bar stay empty for this "
                "engine. Set enable_iter_perf_stats=true to see live numbers.")
        if g("enable_cuda_graphs") is False:
            add("warn", "cuda_graphs_off",
                "Without CUDA graphs every decode step pays full launch overhead and runs noticeably slower. "
                "Turn enable_cuda_graphs back on unless you are debugging.")
        if image != self.default_image:
            add("warn", "image_version_unverified",
                f"The parameters and the generated engine options were read from {self.default_image}. {image} may "
                "rename or remove settings, and the engine refuses names it does not know. Test the launch on "
                "this image before relying on it, or use the pinned one.")
        if hw.arch != "x86_64" and image == self.default_image:
            add("warn", "image_arch_unverified",
                f"The pinned image {self.default_image} was only checked as an amd64 image and this host is "
                f"{hw.arch}. Set image to an arm64 build of the same release.")
        if self._is_multimodal(model) and g("enable_block_reuse") is not False:
            add("warn", "multimodal_block_reuse",
                "TensorRT-LLM's docs say multimodal serving does not work with KV block reuse. Set "
                "enable_block_reuse=false for this model.")
        return out

    @staticmethod
    def _moe_rules(add: _AddFn, params: dict[str, Any], cc_major: int) -> None:
        mb = params.get("moe_backend")
        ep = _as_int(params.get("moe_expert_parallel_size"), 1)
        if mb == "TRTLLM" and cc_major >= 12:
            add("block", "moe_backend_trtllm_sm120",
                "The TRTLLM MoE backend raises 'TRTLLMGenFusedMoE does not support SM120 and above' in this "
                "image. Use CUTLASS (the default).")
        elif mb == "TRITON" and cc_major not in (0, 9) and ep > 1:
            add("block", "moe_backend_triton_ep",
                "The TRITON MoE backend raises 'TritonFusedMoE is only supported on Hopper with EP size > 1' off "
                "Hopper. Set moe_expert_parallel_size to 1 or use CUTLASS (the default).")
        elif mb in ("DEEPGEMM", "CUTEDSL", "WIDEEP", "TRITON") and cc_major >= 12:
            add("warn", "moe_backend_datacenter_only",
                f"The {mb} MoE path is written for Hopper or data-centre Blackwell (its code and NVIDIA's gpt-oss "
                "guide name sm_90 and sm_100/103), and nothing in the image says it runs on sm_120. Use CUTLASS "
                "(the default).")

    @staticmethod
    def _quant_rules(add: _AddFn, model: ModelInfo, params: dict[str, Any], quant: str, sm120: bool,
                     raw: dict[str, Any]) -> None:
        qc = raw.get("quantization_config") if isinstance(raw.get("quantization_config"), dict) else {}
        if sm120 and "fp8" in quant and isinstance(qc, dict) and qc.get("weight_block_size"):
            add("warn", "fp8_block_scaling_sm120",
                "This checkpoint uses block-scaled FP8. TensorRT-LLM's sm_120 column lists FP8 per-tensor but not "
                "block scaling. Use an FP8 per-tensor build (NVIDIA ModelOpt) or an NVFP4 build.")
        if sm120 and ("awq" in quant or "gptq" in quant):
            add("warn", "awq_gptq_sm120",
                "AWQ and GPTQ checkpoints are not listed for sm_120 in TensorRT-LLM's quantization matrix. Use "
                "FP8 or NVFP4, or run this model on vLLM or SGLang.")
        if sm120 and params.get("kv_cache_dtype") == "nvfp4":
            add("warn", "nvfp4_kv_sm120",
                "An NVFP4 KV cache is not listed for sm_120 (and needs a checkpoint prepared for it). Use "
                "kv_cache_dtype fp8 or auto.")
        if any(m in quant for m in ("bitsandbytes", "bnb", "gguf", "exl2", "hqq", "eetq", "quanto", "aqlm")):
            add("warn", "quant_format_unlisted",
                f"'{model.quantization}' is not among TensorRT-LLM's documented quantization recipes (FP8, NVFP4, "
                "MXFP4, AWQ, GPTQ). Use a BF16, FP8 or NVFP4 build of the model.")
        if "mxfp4" in quant and "gpt-oss" not in model.repo_id.lower() and not any(
                "GptOss" in a for a in model.architectures):
            add("warn", "mxfp4_family_unlisted",
                "TensorRT-LLM's support matrix lists MXFP4 for gpt-oss only. Use an FP8 or NVFP4 build of this "
                "model.")

    def _parser_rules(self, add: _AddFn, model: ModelInfo, params: dict[str, Any]) -> None:
        g = params.get
        fam = self._family(model)
        agentic = model.pipeline_tag in (None, "text-generation", "image-text-to-text", "any-to-any")
        tool = g("tool_parser")
        for needles, ok in _TOOL_FAMILIES:
            if any(n in fam for n in needles):
                if tool is None and agentic:
                    add("warn", "tool_parser_mismatch",
                        f"No tool-call parser is set, so tool calls come back as plain text. For this family use "
                        f"tool_parser={' or '.join(ok)}"
                        + (" (qwen3 = JSON in <tool_call>, qwen3_coder = XML <function=...>; the model's chat "
                           "template tells which)." if len(ok) > 1 else "."))
                elif tool is not None and tool not in ok:
                    add("warn", "tool_parser_mismatch",
                        f"tool_parser={tool} does not match this model family's tool-call format; raw tool markup "
                        f"will leak into the answer. Use {' or '.join(ok)}.")
                break
        reasoning = g("reasoning_parser")
        if not any(m in fam for m in _NON_REASONING_MARKERS):
            for needles, parser in _REASONING_FAMILIES:
                if any(n in fam for n in needles):
                    if reasoning is None and agentic:
                        add("warn", "reasoning_parser_mismatch",
                            f"This family writes its reasoning inline; without reasoning_parser={parser} the "
                            "chain of thought stays in the answer text.")
                    elif reasoning is not None and reasoning != parser:
                        add("warn", "reasoning_parser_mismatch",
                            f"reasoning_parser={reasoning} does not match this family; use {parser} so the "
                            "thinking is split off correctly.")
                    break

    # ------------------------------------------------------------------ memory model
    def memory_model(self, model: ModelInfo, params: dict[str, Any]) -> dict[str, float]:
        """TensorRT-LLM sizes the KV cache AFTER loading the weights and a profiling pass:
        pool = free_gpu_memory_fraction x (device total - peak non-KV use) (`KvCacheCreator._cal_max_memory`), so
        the fraction is not a share of the whole card. The estimator budgets `fraction x total` instead, which is
        pessimistic by about (1 - fraction) x weights; the real ceiling is closer to the card's full size.
        Overhead and graph numbers are the estimator's own heuristics, not measurements."""
        g = params.get
        tp, pp, cp = self._world(params)
        world = tp * pp * cp
        out: dict[str, float] = {
            "mem_fraction": _as_float(g("free_gpu_memory_fraction"), 0.9),
            "kv_bytes_per_elem": _KV_BYTES.get(str(g("kv_cache_dtype") or "auto"), 2.0),
            "overhead_gib": 1.0 + 0.5 * (world - 1),
            "cuda_graph_gib": 0.0 if g("enable_cuda_graphs") is False else 1.0,
            "max_batched_tokens": _as_float(g("max_num_tokens"), 8192.0),
            "max_seqs": _as_float(g("max_batch_size"), 2048.0),
            "tp": float(world),
        }
        msl, inferred = _as_int(g("max_seq_len"), 0), _inferred_max_seq_len(model)
        max_len = min(msl, inferred) if msl and inferred else (msl or inferred or model.max_position_embeddings)
        if max_len:
            out["max_len"] = float(max_len)
        cap = _as_float(g("kv_cache_max_gib"), 0.0)
        if cap > 0:
            out["kv_cache_fixed_gib"] = cap             # a cap: the smaller of it and the fraction-based pool
        return out

    def host_memory_gib(self, model: ModelInfo, params: dict[str, Any], hw: Hardware) -> dict[str, float]:
        g = params.get
        out: dict[str, float] = {}
        host = _as_float(g("kv_host_cache_gib"), 0.0)
        if host > 0:
            tp, pp, cp = self._world(params)
            # host_cache_size is read by every worker's own KV manager (resource_manager.calculate_max_num_blocks)
            out["kv_host_cache (per GPU worker)"] = host * tp * pp * cp
        return out

