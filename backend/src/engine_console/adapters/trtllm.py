    # these). `trtllm_` is what the image's Prometheus collector really prints. `/metrics` is one compact JSON line
    # that starts with "[" and has no metric names; the node reads the text before the first "{" or space as the
    # name, which is "[" for that line, so "[" is what lets the iteration statistics through.
