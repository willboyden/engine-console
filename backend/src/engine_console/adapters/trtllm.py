def _inferred_max_seq_len(model: ModelInfo) -> int | None:
    """What the engine derives from the model config when `max_seq_len` is unset or too big
    (`DecoderModelForCausalLM.infer_max_seq_len`, compared with the engine's own output in the tests): the top-level
    `max_position_embeddings`, else the one in `text_config`, else 2048; times the top-level rope factor unless the
    rope type is su, longrope, llama3 or yarn. Without a config dict only `ModelInfo.max_position_embeddings` is
    known, and a model that states nothing yields None rather than a guess."""
    cfg: dict[str, Any] = model.raw_config if isinstance(model.raw_config, dict) else {}
    if not cfg:
        pos = model.max_position_embeddings
        return pos if isinstance(pos, int) and not isinstance(pos, bool) and pos > 0 else None
    inner = cfg.get("text_config")
    text: dict[str, Any] = inner if isinstance(inner, dict) else {}
    pos = cfg.get("max_position_embeddings")
    if pos is None:
        pos = text.get("max_position_embeddings")
    inferred = pos if isinstance(pos, int) and not isinstance(pos, bool) and pos > 0 else 2048
    scaling = cfg.get("rope_scaling")
    factor = 1.0
    if isinstance(scaling, dict):
        rope_type = scaling.get("type", scaling.get("rope_type"))
        raw_factor = scaling.get("factor", 1.0)
        if rope_type not in ("su", "longrope", "llama3", "yarn") and isinstance(raw_factor, (int, float)) \
                and not isinstance(raw_factor, bool) and raw_factor > 0:
            factor = float(raw_factor)
    return math.ceil(inferred * factor) if factor != 1.0 else inferred


def _as_float(val: Any, default: float) -> float:
    """A finite number, or `default`: compatibility() and memory_model() may see unvalidated parameters."""
    if isinstance(val, bool) or not isinstance(val, (int, float)) or not math.isfinite(val):
        return default
    return float(val)


def _as_int(val: Any, default: int) -> int:
    return int(_as_float(val, float(default)))


def _int_list(val: Any) -> list[int]:
    return [int(x) for x in val]


def _gib_to_bytes(val: Any) -> int:
    return int(round(float(val) * _GIB))


def _json_obj(val: Any) -> Any:
    return json.loads(val) if isinstance(val, str) else val


def _image_version(image: str) -> tuple[int, ...] | None:
    m = re.search(r":(\d+)\.(\d+)\.(\d+)", image)
    return tuple(int(x) for x in m.groups()) if m else None


def _set_path(tree: dict[str, Any], path: str, value: Any) -> None:
    """Set `a.b.c` in a nested dict, creating the parents."""
    parts = path.split(".")
    node = tree
    for part in parts[:-1]:
        if part in node and node[part] is None:
            raise ValueError(f"{path}: '{part}' is switched off, so it cannot carry settings")
        child = node.setdefault(part, {})
        if not isinstance(child, dict):
            raise ValueError(f"{path}: '{part}' is already set to a value")
        node = child
    node[parts[-1]] = value


