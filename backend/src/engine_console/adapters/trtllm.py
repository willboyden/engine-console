"""TensorRT-LLM adapter: `trtllm-serve serve` with the PyTorch backend (image `nvcr.io/nvidia/tensorrt-llm/release`).

Launch conventions (the LaunchSpec has no field for them, so the core / node must add them):
  * The image ENTRYPOINT is NVIDIA's `nvidia_entrypoint.sh` (it prepares LD_LIBRARY_PATH, then `exec "$@"`), and the
    image has no default command, so `argv` starts with the program: ``trtllm-serve serve <model> ...``. Skipping
    the entrypoint (`--entrypoint trtllm-serve`) fails to import TensorRT's libraries.
  * docker flags NOT expressible in argv/env: `--ipc=host` (set through `LaunchSpec.ipc_host`), `--gpus` pinning by
    UUID, and `--ulimit memlock=-1 --ulimit stack=67108864`, which the image's own banner recommends and
    `LaunchSpec` cannot carry (the core should add them). Tensor/pipeline parallelism starts MPI workers inside the
    container.
  * `trtllm-serve` has no API-key option and no served-model-name option: any `model` string in a request is
    accepted and `/v1/models` lists the model argument (the repo id, or the directory name for a local folder).
    The console's `served_name` therefore cannot be applied, and the engine port must stay on the internal network.
  * The HF cache is mounted read-only and the engine runs offline (`HF_HUB_OFFLINE=1`): the model must already be
    downloaded, and `snapshot_download` resolves the repo id from `refs/<revision>` inside the mounted cache.
  * No secret is ever placed in argv, env or the generated file: there are none to place.

Settings that the CLI has no flag for (KV block reuse, KV dtype, CUDA graphs, attention backend, speculative
decoding, MoE backend, iteration statistics, ...) go into a generated YAML file, written by the node from
`LaunchSpec.files` and passed with `--extra_llm_api_options`. The engine deep-merges `kv_cache_config` with the CLI's
`--free_gpu_memory_fraction` but replaces every other nested block wholesale; `scheduler_config` is therefore always
emitted with the stock defaults of `commands/serve.py::get_llm_args` restated.

Console default: iteration statistics (`enable_iter_perf_stats: true`, history `max_stats_len: 100`) are switched on
unless the user sets `enable_iter_perf_stats` to false, because without them `/metrics` stays an empty array and
the console has nothing to show for this engine. That makes the file present on nearly every launch (set
`_METRICS_ON_BY_DEFAULT = False` to emit it only when a YAML parameter is set).

Metrics caveat (read from `serve/openai_server.py` and `executor/`, see trtllm_parse.py): `/metrics` is a JSON array,
not Prometheus, and every request to it takes at least two seconds because the engine waits for more statistics
before it answers. A scraper whose read timeout is two seconds or less can never succeed.
"""
